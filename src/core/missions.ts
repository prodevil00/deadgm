// The campaign. Each mission is data: gates, hordes, crates, walls, hazards and an optional boss.
// Lanes: left ≈ x -2.6, centre 0, right ≈ +2.6 (road is ±5.2 m).

import type { CrateReward, EnemyMix, GateSpec, MissionDef, MissionEvent, Side } from './types';

// ------------------------------------------------------------------ builders
const add = (value: number, grow?: number, max?: number): GateSpec => ({ kind: 'add', value, grow, max });
const mul = (value: number): GateSpec => ({ kind: 'mul', value });
const gun = (value = 1, grow?: number): GateSpec => ({ kind: 'weapon', value, grow, max: 3 });
const heal = (seconds = 4): GateSpec => ({ kind: 'heal', value: seconds });
const rate = (pct = 20): GateSpec => ({ kind: 'rate', value: pct });
const dmg = (pct = 20): GateSpec => ({ kind: 'dmg', value: pct });

const pair = (z: number, L: GateSpec, R: GateSpec): MissionEvent => ({ type: 'gates', z, gates: { L, R } });
const single = (z: number, side: Side, g: GateSpec): MissionEvent => ({ type: 'gates', z, gates: { [side]: g } });
const horde = (z: number, count: number, mix: EnemyMix = { walker: 1 }, o: { x?: number; spread?: number; depth?: number } = {}): MissionEvent =>
  ({ type: 'horde', z, count, mix, ...o });
const crate = (z: number, x: number, hits: number, reward: CrateReward): MissionEvent => ({ type: 'crate', z, x, hits, reward });
const wall = (z: number, x: number, w: number, d = 1.4, kind: 'barrier' | 'wreck' | 'truck' | 'container' = 'barrier'): MissionEvent =>
  ({ type: 'wall', z, x, w, d, kind });
const fire = (z: number, x: number, w: number, d = 4): MissionEvent => ({ type: 'hazard', z, x, w, d, kind: 'fire' });
const acid = (z: number, x: number, w: number, d = 4): MissionEvent => ({ type: 'hazard', z, x, w, d, kind: 'acid' });
const surv = (z: number, x: number, n: number): MissionEvent => ({ type: 'survivors', z, x, n });
const barrel = (z: number, x: number): MissionEvent => ({ type: 'barrel', z, x });
const mutant = (z: number, x = 0): MissionEvent => ({ type: 'enemy', z, enemy: 'heavy', x });
const spitter = (z: number, x = 0): MissionEvent => ({ type: 'enemy', z, enemy: 'elite', x });

const LEFT = -2.6, RIGHT = 2.6;
const W = { walker: 1 };
const WR = (r: number) => ({ walker: 1 - r, runner: r });

